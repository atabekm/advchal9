"""A review → the Markdown of the PR comment.

The comment starts with MARKER, so the next run finds it and edits it instead of adding another.
Lines link to the reviewed commit on GitHub when the repository's URL is known.
"""

from __future__ import annotations

from .review import Finding, Review

MARKER = "<!-- devreview -->"
SECTIONS = [("bug", "Potential bugs"), ("architecture", "Architectural issues"), ("recommendation", "Recommendations")]
BADGE = {"high": "🔴 high", "medium": "🟠 medium", "low": "⚪ low"}


def markdown(review: Review, repo_url: str = "") -> str:
    out = [MARKER, "## Automated review", ""]
    reviewed = len(review.files)
    errors = [fr for fr in review.files if fr.error]
    head = f"[`{review.head[:7]}`]({repo_url}/commit/{review.head})" if repo_url else f"`{review.head[:7]}`"
    out.append(f"Commit {head} · {reviewed} file{'s' * (reviewed != 1)} reviewed, {len(review.skipped)} skipped · "
               f"`{review.model}` on a self-hosted runner · {_duration(review.seconds)}")
    out.append("")
    counts = {k: sum(f.kind == k for f in review.findings) for k, _ in SECTIONS}
    if not review.findings:
        out.append("No issues found in the changed code." if reviewed else "Nothing to review: no code files changed.")
        out.append("")
    for kind, heading in SECTIONS:
        if not counts[kind]:
            continue
        out += [f"### {heading} ({counts[kind]})", ""]
        for f in sorted((f for f in review.findings if f.kind == kind), key=lambda f: (_sev(f), f.file, f.line or 0)):
            out.append(_item(f, review.head, repo_url))
        out.append("")
    if errors:
        out += ["### Not reviewed (errors)", ""]
        out += [f"- `{fr.path}`: {fr.error}" for fr in errors]
        out.append("")
    out += _details(review)
    out += ["", "<sub>Generated by devreview (task 32): a local model reviewing the diff with the repository's docs "
            "and code as context. It can be wrong; findings are suggestions, not verdicts.</sub>"]
    return "\n".join(out)


def _item(f: Finding, head: str, repo_url: str) -> str:
    where = f"{f.file}:{f.line}" if f.line else f.file
    link = f"{repo_url}/blob/{head}/{f.file}" + (f"#L{f.line}" if f.line else "") if repo_url else ""
    loc = f"[`{where}`]({link})" if link else f"`{where}`"
    text = f"- **{BADGE[f.severity]}** {loc}: **{_md(f.title)}**"
    if f.detail and f.detail != f.title:
        text += f"  \n  {_md(f.detail)}"
    if f.sources:
        text += "  \n  <sub>based on: " + "; ".join(f"`{s}`" for s in f.sources) + "</sub>"
    return text


def _details(review: Review) -> list[str]:
    out = ["<details><summary>What the reviewer looked at</summary>", ""]
    for fr in review.files:
        la = fr.looked_at
        bits = []
        if la.get("changed"):
            bits.append("changed " + ", ".join(f"`{n}`" for n in la["changed"]))
        if la.get("removed"):
            bits.append("removed " + ", ".join(f"`{n}`" for n in la["removed"]))
        if la.get("dangling"):
            bits.append("still used after removal: " + ", ".join(f"`{n}` ({len(u)})" for n, u in la["dangling"].items()))
        if la.get("callers"):
            bits.append("call sites of " + ", ".join(f"`{n}` ({c})" for n, c in la["callers"].items()))
        if la.get("definitions"):
            bits.append("definitions of " + ", ".join(f"`{d.split(' ')[0]}`" for d in la["definitions"]))
        timing = f"{fr.prompt_tokens}+{fr.completion_tokens} tokens, {fr.seconds:.0f}s" if not fr.error else "error"
        out.append(f"- `{fr.path}` ({timing}): " + ("; ".join(bits) or "no definitions touched"))
        if la.get("passages"):
            out.append("  - passages: " + "; ".join(f"`{p}`" for p in la["passages"]))
    if review.skipped:
        out += ["", "Skipped: " + ", ".join(f"`{p}` ({r})" for p, r in review.skipped)]
    out += ["", "</details>"]
    return out


def _sev(f: Finding) -> int:
    return ["high", "medium", "low"].index(f.severity)


def _md(text: str) -> str:
    return text.replace("<", "&lt;").replace(">", "&gt;")


def _duration(seconds: float) -> str:
    m, s = divmod(int(seconds), 60)
    return f"{m}m {s:02d}s" if m else f"{s}s"


def terminal(review: Review, color: bool = True) -> str:
    """The same review for a terminal."""
    b, d, r = ("\033[1m", "\033[2m", "\033[0m") if color else ("", "", "")
    sev = {"high": "\033[31m", "medium": "\033[33m", "low": "\033[2m"} if color else {}
    out = [f"{b}{review.title}{r}  {d}{review.base[:7]}..{review.head[:7]} · {len(review.files)} files reviewed · "
           f"{review.model} · {_duration(review.seconds)}{r}"]
    for kind, heading in SECTIONS:
        items = [f for f in review.findings if f.kind == kind]
        if not items:
            continue
        out += ["", f"{b}{heading}{r}"]
        for f in sorted(items, key=lambda f: (_sev(f), f.file, f.line or 0)):
            where = f"{f.file}:{f.line}" if f.line else f.file
            out.append(f"  {sev.get(f.severity, '')}{f.severity:6}{r if color else ''} {where}  {b}{f.title}{r}")
            if f.detail and f.detail != f.title:
                out.append(f"         {f.detail}")
            if f.sources:
                out.append(f"         {d}based on: {'; '.join(f.sources)}{r}")
            if f.note:
                out.append(f"         {d}({f.note}){r}")
    if not review.findings:
        out += ["", "No issues found."]
    for fr in review.files:
        if fr.error:
            out.append(f"{d}error in {fr.path}: {fr.error}{r}")
    out.append("")
    out.append(d + "  ".join(f"{fr.path} {fr.seconds:.0f}s" for fr in review.files) + r)
    return "\n".join(out)
